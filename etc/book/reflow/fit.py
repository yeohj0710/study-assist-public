def fit_map(x,y,w,h):
    left=x+20
    poly([(left,y+47),(left+52,y+17),(left+86,y+26),(left+121,y+17),(left+176,y+47),
          (left+162,y+81),(left+143,y+70),(left+148,y+195),(left+29,y+195),
          (left+32,y+70),(left+12,y+82)],'#334D45')
    line(left+87,y+27,left+87,y+194,'#90AA9E',1.2)
    a=(left+86,y+54)
    b=(left+120,y+101)
    cpt=(left+138,y+167)
    d=(left+146,y+89)
    line(*a,left+88,y+84,'#F0BC60',2.7)
    line(left+88,y+84,*b,'#F0BC60',2.7)
    line(*b,left+117,y+141,'#76B5F4',2.7)
    line(left+117,y+141,*cpt,'#76B5F4',2.7)
    line(*b,*d,'#BE9DEB',2.7)
    for label,(px,py),tone in [('A',a,AMBER),('B',b,GREEN),('C',cpt,BLUE),('D',d,PURPLE)]:
        circle(px,py,9,tone)
        txt(px,py-8,label,11,'ExtraBold',WHITE,'center')
    for i,(name,detail,color) in enumerate((
        ('A  카메라','목 아래 가운데 버튼 부근',AMBER),
        ('B  보드','A에서 아래 10~16cm, 옆 5~7cm',GREEN),
        ('D  진동','보드 B 바로 옆, 같은 쪽',PURPLE),
        ('C  배터리','같은 쪽 옆구리 안주머니',BLUE),
    )):
        yy=y+9+46*i
        rect(x+224,yy,w-225,38,WHITE,LINE,7)
        txt(x+241,yy+5,name,11.5,'ExtraBold',color)
        txt(x+241,yy+21,detail,9.1,'Medium',GRAY)


